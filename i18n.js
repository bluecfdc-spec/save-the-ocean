  const KEY = 'savetheocean_lang';
  const LANGS = ['ko', 'en', 'ja'];
  function detect() {
    const q = new URLSearchParams(location.search).get('lang');
    if (LANGS.includes(q)) { localStorage.setItem(KEY, q); return q; }
    const saved = localStorage.getItem(KEY);
    if (LANGS.includes(saved)) return saved;
    const nav = ((navigator.languages && navigator.languages[0]) || navigator.language || 'en').toLowerCase();
    return nav.startsWith('ko') ? 'ko' : nav.startsWith('ja') ? 'ja' : 'en';
  }
  let lang = detect();

  const I18N = {
    get lang() { return lang; },
    t(key, vars) {
      let s = (DICT[lang] && DICT[lang][key]) || DICT.ko[key] || key;
      if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
      return s;
    },
    set(l) { lang = LANGS.includes(l) ? l : 'en'; localStorage.setItem(KEY, lang); I18N.apply(); },
    toggle() { I18N.set(LANGS[(LANGS.indexOf(lang) + 1) % LANGS.length]); },
    // data-i18n 속성이 붙은 요소 전부 갱신
    apply() {
      document.documentElement.lang = lang;
      document.title = I18N.t('app.title');
      document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = I18N.t(el.getAttribute('data-i18n')); });
      document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = I18N.t(el.getAttribute('data-i18n-ph')); });
      document.querySelectorAll('[data-i18n-label]').forEach(el => { el.setAttribute('aria-label', I18N.t(el.getAttribute('data-i18n-label'))); });
      document.dispatchEvent(new CustomEvent('i18n:change', { detail: { lang } }));
    },
    // 숫자 표기 (1,234 / 1.2K)
    num(n) { return Number(n).toLocaleString(lang === 'ko' ? 'ko-KR' : lang === 'ja' ? 'ja-JP' : 'en-US'); }
  };
  window.I18N = I18N;
  window.t = I18N.t;
